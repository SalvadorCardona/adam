/** How long is left, in words: "42 min", "1 min", "less than a minute". */
const remaining = (ms: number): string => {
  const minutes = Math.ceil(ms / 60_000);

  return ms <= 0 ? 'expired' : minutes <= 1 ? 'less than a minute' : `${minutes} min`;
};

